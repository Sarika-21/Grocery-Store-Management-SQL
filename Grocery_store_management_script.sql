-- Q4. What are the monthly trends in order volume and revenue? 

-- DATA TYPE CORRECTION:
-- UPDATE is used to convert the existing VARCHAR date values into a DATE format
-- using STR_TO_DATE().
-- ALTER TABLE is used to modify the column's datatype from VARCHAR to DATE.
-- This ensures that date functions such as MONTH(), YEAR(), and DAYNAME()
-- can be used directly for accurate date-based analysis.
UPDATE orders
SET order_date = STR_TO_DATE(order_date, '%c/%e/%Y');
ALTER TABLE orders
MODIFY COLUMN order_date DATE;

SELECT
	MONTH(o.order_date) AS order_month,
    COUNT(DISTINCT o.ord_id) AS total_orders,
    SUM(od.total_price) AS total_revenue
FROM order_details od
JOIN orders o
	ON o.ord_id = od.ord_id
GROUP BY MONTH(o.order_date)
ORDER BY order_month;

-- Q5. How do order patterns vary across weekdays and weekends? 
SELECT
    CASE
        WHEN DAYOFWEEK(order_date) IN (1, 7) THEN 'Weekend'
        ELSE 'Weekday'
    END AS day_type,
    COUNT(ord_id) AS total_orders
FROM orders
GROUP BY day_type;

