	p.prod_id,
    p.prod_name,
	ROUND(AVG(quantity),2) AS average_quantity
FROM order_details od
JOIN products p
	ON p.prod_id = od.prod_id
GROUP BY od.prod_id, p.prod_name;

-- Q3. How does the unit price vary across products and orders? 
SELECT
    p.prod_id,
    p.prod_name,
    MIN(each_price) AS minimum_unit_price,
    MAX(each_price) AS maximum_unit_price,
    ROUND(AVG(each_price),2) AS average_unit_price
FROM order_details od
JOIN products p
	ON p.prod_id = od.prod_id
GROUP BY od.prod_id
ORDER BY p.prod_id;

SELECT
    prod_id,
    MIN(each_price) AS min_price,
    MAX(each_price) AS max_price
FROM order_details
GROUP BY prod_id
HAVING MIN(each_price) <> MAX(each_price);

-- ANALYSIS:
-- Compared minimum and maximum unit prices for each product
-- across all recorded orders.
-- No price variations were identified.
-- All products maintained consistent unit prices across orders.

